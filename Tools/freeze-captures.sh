#!/usr/bin/env bash
#
# Freeze every capture under captures/ into one Swift corpus.
#
# A capture is a directory:
#
#   captures/<id>/frames.hex     the recording:  <name> = <hex bytes>
#   captures/<id>/capture.json   its provenance: model, firmware, tool, date, channel
#
# The .hex grammar is the same one the single-device app used, because it is a good one:
#
#   * a line starting with '#' is a comment
#   * a run of comment lines directly above an entry becomes that entry's note
#   * the comment block before the first entry is the file header and is discarded
#     (the capture's own prose lives in capture.json where it is a field, not a comment)
#   * a line containing '=' is an entry: name = hex, split on the first '='
#   * blank lines are skipped
#
# Nothing is ever transcribed by hand. This script does not invent a byte, does not
# correct a frame, and does not skip an unparseable one: an entry it cannot read is a
# hard error, because a fixture that silently disappears is worse than a build that stops.
#
# Usage:  ./Tools/freeze-captures.sh

set -euo pipefail

cd "$(dirname "$0")/.."

python3 - <<'PY'
import json
import os
import sys

CAPTURES = "captures"
OUT = os.path.join("Sources", "BudsCore", "CaptureCorpus.swift")

def die(msg):
    sys.stderr.write("freeze-captures: %s\n" % msg)
    sys.exit(1)

def swift_string(s):
    out = s.replace("\\", "\\\\").replace('"', '\\"')
    out = out.replace("\n", "\\n")
    return '"%s"' % out

def parse_frames(path):
    """Return [(name, note, hex)] in file order. Notes are the comment run above the entry."""
    entries = []
    note_lines = []
    with open(path, encoding="utf-8") as fh:
        for lineno, raw in enumerate(fh, 1):
            line = raw.rstrip("\n")
            if line.startswith("#"):
                note_lines.append(line[1:].strip())
                continue
            if not line.strip():
                continue
            if "=" not in line:
                die("%s:%d: not a comment and not an entry: %r" % (path, lineno, line))
            name, _, hexstr = line.partition("=")
            name = name.strip()
            hexstr = " ".join(hexstr.split())
            if not name:
                die("%s:%d: entry with an empty name" % (path, lineno))
            if not hexstr:
                die("%s:%d: entry %r has no bytes" % (path, lineno, name))
            for tok in hexstr.split(" "):
                try:
                    byte = int(tok, 16)
                except ValueError:
                    die("%s:%d: entry %r has a non-hex token %r" % (path, lineno, name, tok))
                if not (0 <= byte <= 0xFF) or len(tok) > 2:
                    die("%s:%d: entry %r has an out-of-range byte %r" % (path, lineno, name, tok))
            note = " ".join(note_lines).strip()
            entries.append((name, note, hexstr))
            note_lines = []
    # A trailing comment run with no entry after it is a dangling note: a mistake.
    if any(n for n in note_lines):
        die("%s: trailing comment with no entry under it: %r" % (path, " ".join(note_lines)))
    return entries

if not os.path.isdir(CAPTURES):
    die("no %s/ directory" % CAPTURES)

ids = sorted(d for d in os.listdir(CAPTURES) if os.path.isdir(os.path.join(CAPTURES, d)))
if not ids:
    die("no captures found under %s/" % CAPTURES)

recordings = []
for cid in ids:
    base = os.path.join(CAPTURES, cid)
    manifest = os.path.join(base, "capture.json")
    frames = os.path.join(base, "frames.hex")
    if not os.path.isfile(manifest):
        die("%s has no capture.json" % base)
    if not os.path.isfile(frames):
        die("%s has no frames.hex" % base)
    with open(manifest, encoding="utf-8") as fh:
        prov = json.load(fh)
    for field in ("id", "date", "model", "vendor", "firmware", "firmwareSource", "tool", "host"):
        if field not in prov:
            die("%s: capture.json is missing %r" % (base, field))
    if prov["id"] != cid:
        die("%s: capture.json id %r does not match its directory name" % (base, prov["id"]))
    service = prov.get("service", {})
    for field in ("name", "uuid", "rfcommChannel"):
        if field not in service:
            die("%s: capture.json service is missing %r" % (base, field))
    entries = parse_frames(frames)
    if not entries:
        die("%s: no entries" % frames)
    declared = prov.get("frames")
    if declared is not None and declared != len(entries):
        die("%s: capture.json says %d frames, frames.hex has %d"
            % (base, declared, len(entries)))
    recordings.append((prov, entries))

lines = []
w = lines.append

w("// Generated by Tools/freeze-captures.sh -- do not edit by hand.")
w("// Regenerate with: ./Tools/freeze-captures.sh")
w("//")
w("// Source of truth: captures/<id>/frames.hex (+ capture.json for provenance).")
w("// A test asserts this file and those recordings agree byte for byte, so a frame")
w("// whose varint length disagrees with its payload-length field cannot exist here.")
w("")
w("public enum CaptureCorpus {")
w("    /// Where a recording came from. Every frame carries one, because once there is")
w("    /// more than one device, \"which model said this\" stops being decoration.")
w("    public struct Provenance: Sendable, Equatable {")
w("        public let id: String")
w("        public let date: String")
w("        public let model: String")
w("        public let vendor: String")
w("        /// The version string exactly as the hardware reports it, verbatim.")
w("        public let firmware: String")
w("        /// How that string was obtained -- it is not necessarily a dotted version.")
w("        public let firmwareSource: String")
w("        public let serviceName: String")
w("        public let serviceUUID: String")
w("        public let rfcommChannel: Int")
w("        public let tool: String")
w("        public let host: String")
w("        public let notes: String")
w("")
w("        public init(id: String, date: String, model: String, vendor: String, firmware: String,")
w("                    firmwareSource: String, serviceName: String, serviceUUID: String,")
w("                    rfcommChannel: Int, tool: String, host: String, notes: String) {")
w("            self.id = id")
w("            self.date = date")
w("            self.model = model")
w("            self.vendor = vendor")
w("            self.firmware = firmware")
w("            self.firmwareSource = firmwareSource")
w("            self.serviceName = serviceName")
w("            self.serviceUUID = serviceUUID")
w("            self.rfcommChannel = rfcommChannel")
w("            self.tool = tool")
w("            self.host = host")
w("            self.notes = notes")
w("        }")
w("    }")
w("")
w("    /// One frame off the wire, with the note the capture gave it.")
w("    public struct Capture: Sendable {")
w("        public let name: String")
w("        public let note: String")
w("        public let hex: String")
w("        public let provenance: Provenance")
w("")
w("        public init(name: String, note: String, hex: String, provenance: Provenance) {")
w("            self.name = name")
w("            self.note = note")
w("            self.hex = hex")
w("            self.provenance = provenance")
w("        }")
w("")
w("        public var bytes: [UInt8] {")
w("            hex.split(separator: \" \").compactMap { UInt8($0, radix: 16) }")
w("        }")
w("    }")
w("")
w("    /// One recording session: the provenance, and the frames in capture order.")
w("    public struct Recording: Sendable {")
w("        public let provenance: Provenance")
w("        public let frames: [Capture]")
w("")
w("        public init(provenance: Provenance, frames: [Capture]) {")
w("            self.provenance = provenance")
w("            self.frames = frames")
w("        }")
w("    }")
w("")
w("    /// One entry per recording, so a frame can point at its provenance cheaply.")
w("    private static let provenances: [Provenance] = [")
for prov, _ in recordings:
    w("        Provenance(")
    w("            id: %s," % swift_string(prov["id"]))
    w("            date: %s," % swift_string(prov["date"]))
    w("            model: %s," % swift_string(prov["model"]))
    w("            vendor: %s," % swift_string(prov["vendor"]))
    w("            firmware: %s," % swift_string(prov["firmware"]))
    w("            firmwareSource: %s," % swift_string(prov["firmwareSource"]))
    w("            serviceName: %s," % swift_string(prov["service"]["name"]))
    w("            serviceUUID: %s," % swift_string(prov["service"]["uuid"]))
    w("            rfcommChannel: %d," % prov["service"]["rfcommChannel"])
    w("            tool: %s," % swift_string(prov["tool"]))
    w("            host: %s," % swift_string(prov["host"]))
    w("            notes: %s" % swift_string(prov.get("notes", "")))
    w("        ),")
w("    ]")
w("")
w("    public static let recordings: [Recording] = [")
for index, (_, entries) in enumerate(recordings):
    w("        Recording(")
    w("            provenance: provenances[%d]," % index)
    w("            frames: [")
    for name, note, hexstr in entries:
        w("                Capture(")
        w("                    name: %s," % swift_string(name))
        w("                    note: %s," % swift_string(note))
        w("                    hex: %s," % swift_string(hexstr))
        w("                    provenance: provenances[%d]" % index)
        w("                ),")
    w("            ]")
    w("        ),")
w("    ]")
w("")
w("    /// Every frame from every recording, in recording then capture order.")
w("    public static var frames: [Capture] { recordings.flatMap(\\.frames) }")
w("")
w("    public static var frameCount: Int { recordings.reduce(0) { $0 + $1.frames.count } }")
w("}")
w("")

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("\n".join(lines))

total = sum(len(e) for _, e in recordings)
print("freeze-captures: wrote %s (%d recording(s), %d frames)" % (OUT, len(recordings), total))
PY
